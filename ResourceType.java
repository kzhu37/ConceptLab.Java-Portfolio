
/**
 * Supported categories for external learning resources.
 */
public enum ResourceType {
    /**
     * Interactive tool or web app that allows active manipulation.
     */
    INTERACTIVE,
    /**
     * Simulation focused on modeling behavior over time.
     */
    SIMULATION,
    /**
     * Diagram or visual reference asset.
     */
    DIAGRAM,
    /**
     * Written explainer content.
     */
    ARTICLE,
    /**
     * Video lesson or walkthrough.
     */
    VIDEO,
    /**
     * Practice activity or problem set.
     */
    PRACTICE,
    /**
     * Reference style material such as textbook pages or docs.
     */
    REFERENCE,
    /**
     * Catch-all for resources that do not fit the primary categories.
     */
    OTHER
}
